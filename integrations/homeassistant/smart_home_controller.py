#!/usr/bin/env python3
"""
litrun Edge Home Assistant Controller
Example script showing how to use litrun's OpenAI-compatible REST server
with structured JSON schema enforcement to convert raw IoT sensor telemetry into
safe, executable Home Assistant service actions without cloud round-trips.
"""

import json
import urllib.request
import urllib.error
import sys

LITRUN_URL = "http://localhost:8080/v1/chat/completions"

# Exact Home Assistant Action Schema
HA_ACTION_SCHEMA = {
    "type": "object",
    "properties": {
        "domain": {
            "type": "string",
            "enum": ["light", "climate", "switch", "notify", "cover"]
        },
        "service": {
            "type": "string",
            "enum": ["turn_on", "turn_off", "toggle", "set_temperature", "send_message"]
        },
        "entity_id": {
            "type": "string"
        },
        "reason": {
            "type": "string"
        }
    },
    "required": ["domain", "service", "entity_id", "reason"]
}


def evaluate_sensor_event(sensor_telemetry: dict) -> dict:
    prompt = (
        f"You are an offline Home Assistant automation edge agent.\n"
        f"Sensor telemetry readings: {json.dumps(sensor_telemetry)}\n"
        f"Generate the exact Home Assistant action required based on these readings."
    )

    payload = {
        "model": "qwen2.5-0.5b",
        "messages": [
            {"role": "system", "content": "You are a deterministic IoT controller."},
            {"role": "user", "content": prompt}
        ],
        "response_format": {
            "type": "json_schema",
            "json_schema": {"schema": HA_ACTION_SCHEMA}
        },
        "stream": False
    }

    req = urllib.request.Request(
        LITRUN_URL,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"}
    )

    try:
        with urllib.request.urlopen(req, timeout=15) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            content = data["choices"][0]["message"]["content"]
            action = json.loads(content)
            return action
    except urllib.error.URLError as e:
        print(f"Error connecting to litrun on {LITRUN_URL}: {e}")
        sys.exit(1)


if __name__ == "__main__":
    print("⚡ litrun Edge Home Assistant Controller Demo")
    print("Simulating high room temperature trigger...")

    telemetry = {
        "room": "living_room",
        "temperature_celsius": 28.5,
        "humidity_percent": 65,
        "motion_detected": True,
        "ac_state": "off"
    }

    action = evaluate_sensor_event(telemetry)
    print("\n✓ Valid Action Generated by Local LLM:")
    print(json.dumps(action, indent=2))
